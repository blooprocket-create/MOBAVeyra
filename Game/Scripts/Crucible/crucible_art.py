"""What stands on the masses' tops (ADR-073 §5), derived from World.json's generated masses and the style profile's massArt.

For each of Team A's masses it writes what stands on its top: on a forest its canopy of trees and shrubs and the shrubs
round its rim, on cliffs and rocks sparse shrubs and boulders, all inset from the gameplay edge past where the sculpted
face steps back. The masses' own shape is sculpted in
VeyraWorldTools from the style profile's massForms, so it is not written here.

Team B's are the half turn of Team A's, so only Team A's are written. Presentation only: VeyraWorldTools places what
this writes; nothing here changes what blocks. Needs shapely (requirements.txt beside this file) for everything but the
hashes.
"""
from __future__ import annotations

import hashlib
import json
import random
from pathlib import Path

from crucible_geometry import REPO

STYLE_JSON = REPO / "Game" / "Plugins" / "VeyraWorldTools" / "Config" / "CrucibleStyle.json"
ART_JSON = REPO / "Game" / "Plugins" / "VeyraWorldTools" / "Config" / "CrucibleMassArt.json"


def load_style(path: Path = STYLE_JSON) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def profile_sha256(style: dict) -> str:
    canonical = json.dumps(style["massArt"], sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


def _parts(geom):
    if geom.is_empty:
        return []
    return [g for g in (geom.geoms if hasattr(geom, "geoms") else [geom]) if g.geom_type == "Polygon" and not g.is_empty]


def _by_share(shares: dict, draw: float):
    """The piece a draw in [0, 1) picks from shares taken in their order, or None past their sum: that spot stays bare."""
    total = 0.0
    for kind, share in shares.items():
        total += share
        if draw < total:
            return kind
    return None


def derive_art(world: dict, style: dict) -> dict:
    from shapely.geometry import Point, Polygon

    art = style["massArt"]
    seed = art["seed"]
    team_a = [m for m in world["layout"]["masses"]["items"] if m["id"].startswith("a")]
    masses = []
    for index, mass in enumerate(team_a):
        outline = Polygon([(p["x"], p["y"]) for p in mass["points"]])
        canopy = []
        spec = art["canopy"].get(mass["kind"])
        if spec:
            rng = random.Random(seed + index)
            inner = outline.buffer(-spec["inset"])
            minx, miny, maxx, maxy = outline.bounds
            y = miny + rng.uniform(0, spec["spacing"])
            while y < maxy:
                x = minx + rng.uniform(0, spec["spacing"])
                while x < maxx:
                    px, py = x + rng.uniform(-spec["jitter"], spec["jitter"]), y + rng.uniform(-spec["jitter"], spec["jitter"])
                    if inner.contains(Point(px, py)):
                        kind = _by_share(spec["share"], rng.random())
                        scale, yaw = round(rng.uniform(*spec["scale"]), 2), round(rng.uniform(0, 360), 1)
                        if kind:
                            canopy.append({"at": [round(px, 1), round(py, 1)], "kind": kind, "scale": scale, "yaw": yaw})
                    x += spec["spacing"]
                y += spec["spacing"]
            if spec["rimSpacing"] > 0:
                for part in _parts(outline.buffer(-spec["rimInset"])):
                    rim = part.exterior
                    along = 0.0
                    while along < rim.length:
                        p = rim.interpolate(along)
                        canopy.append({"at": [round(p.x, 1), round(p.y, 1)], "kind": "Shrub",
                                       "scale": round(rng.uniform(*spec["rimScale"]), 2), "yaw": round(rng.uniform(0, 360), 1)})
                        along += spec["rimSpacing"]
        masses.append({"id": mass["id"], "kind": mass["kind"], "canopy": canopy})
    return {
        "description": "GENERATED by Game/Scripts/Crucible/BuildCrucibleMassArt.py from World.json's masses and CrucibleStyle.json's massArt; never edit by hand (ADR-073 §5). Team A's masses only: Team B's are their half turn.",
        "massesInputSha256": world["layout"]["masses"]["inputSha256"],
        "profileSha256": profile_sha256(style),
        "masses": masses,
    }


def farthest_step_back(form: dict) -> float:
    """How far a kind's sculpted face may step back from its gameplay edge at most: its profile's deepest share of
    insetMax, with the full bulge and fissure on top."""
    return form["insetMax"] * max(share for _, share in form["profile"]) + form["bulge"] + form["fissure"]
